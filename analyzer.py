#!/usr/bin/env python3
"""website-bug-analyzer: audit a public web page for common bugs and estimate
whether it was likely built with an AI website builder or by a human.

Usage:
    python3 analyzer.py https://example.com [--json]

The audit covers HTTP status, redirects and response time, HTTPS, security
headers, basic SEO, broken links and images, mixed content, and oversized
unminified assets. The AI-vs-human verdict is a heuristic guess based on
public signals (meta generator, builder footers, generic copy, stock photos)
and is labelled as such in the output -- it is not proof.

Standard library only. No network access beyond the page being audited.
"""

import argparse
import html.parser
import json
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

VERSION = "1.0.0"
USER_AGENT = (
    "website-bug-analyzer/1.0 "
    "(+https://github.com/Akbar-Lab-Droid/website-bug-analyzer)"
)
REQUEST_TIMEOUT = 10
MAX_LINKS_TO_CHECK = 30
MAX_IMAGES_TO_CHECK = 30
LARGE_ASSET_BYTES = 200_000  # unminified asset above this is worth flagging

# Health points deducted per finding.
POINTS = {"high": 12, "medium": 6, "low": 3}

SECURITY_HEADERS = {
    "strict-transport-security": "Strict-Transport-Security",
    "content-security-policy": "Content-Security-Policy",
    "x-frame-options": "X-Frame-Options",
    "x-content-type-options": "X-Content-Type-Options",
    "referrer-policy": "Referrer-Policy",
}

# Meta generator values that point at AI-first website builders (strong) or
# at template builders where a human still does most of the work (weak).
AI_GENERATORS = {
    "durable": "strong",
    "gamma": "strong",
    "mixo": "strong",
    "hocoos": "strong",
    "10web": "strong",
    "bookmark": "strong",
    "zyro": "strong",
    "wix adi": "strong",
    "jimdo dolphin": "strong",
    "hostinger ai": "strong",
    "framer": "weak",
    "webflow": "weak",
}

# Footer / badge phrases left behind by builders. Searched in page text.
BUILDER_PHRASES = [
    "made with durable",
    "built with durable",
    "created with durable",
    "made with gamma",
    "created with gamma",
    "made with mixo",
    "built with mixo",
    "made with hocoos",
    "built with 10web",
    "made with bookmark",
    "created with bookmark",
    "made with framer",
    "built with framer",
    "powered by wix",
    "made with wix",
    "created with jimdo",
    "powered by jimdo",
    "built with ai",
    "generated by ai",
    "created with ai",
]

# Copy that shows up again and again in AI-written marketing pages. One
# phrase alone means little; several together is a real signal.
GENERIC_PHRASES = [
    "in today's fast-paced world",
    "unlock the power of",
    "welcome to the future of",
    "in the digital age",
    "elevate your",
    "supercharge your",
    "game-changer",
    "cutting-edge solution",
    "seamless experience",
    "revolutionize the way",
    "empower your",
    "leverage the power",
    "delve into",
    "take your business to the next level",
]

STOCK_PHOTO_HOSTS = (
    "images.unsplash.com",
    "images.pexels.com",
    "cdn.pixabay.com",
    "picsum.photos",
    "placehold.co",
    "via.placeholder.com",
    "loremflickr.com",
    "dummyimage.com",
)


class PageParser(html.parser.HTMLParser):
    """Collects the bits of a page the audit needs: metadata, headings,
    links, images, stylesheets, scripts, and visible text."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.title = ""
        self._in_title = False
        self.meta = {}
        self.lang = ""
        self.canonical = ""
        self.headings = []  # list of (level, text)
        self._heading_level = 0
        self._heading_text = ""
        self.links = []  # raw href values from <a>
        self.images = []  # dicts: src, alt, width, height
        self.stylesheets = []
        self.scripts = []
        self.text_parts = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "title":
            self._in_title = True
        elif tag == "html":
            self.lang = attrs.get("lang", "")
        elif tag == "meta":
            name = attrs.get("name", "").lower()
            if name:
                self.meta[name] = attrs.get("content", "")
        elif tag == "link":
            rel = attrs.get("rel", "").lower()
            if rel == "canonical":
                self.canonical = attrs.get("href", "")
            elif rel == "stylesheet":
                self.stylesheets.append(attrs.get("href", ""))
        elif tag in ("h1", "h2", "h3", "h4", "h5", "h6"):
            self._heading_level = int(tag[1])
            self._heading_text = ""
        elif tag == "a":
            self.links.append(attrs.get("href", ""))
        elif tag == "img":
            self.images.append(
                {
                    "src": attrs.get("src", ""),
                    "alt": attrs.get("alt"),
                    "width": attrs.get("width"),
                    "height": attrs.get("height"),
                }
            )
        elif tag == "script":
            src = attrs.get("src", "")
            if src:
                self.scripts.append(src)

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False
        elif tag in ("h1", "h2", "h3", "h4", "h5", "h6") and self._heading_level:
            self.headings.append((self._heading_level, self._heading_text.strip()))
            self._heading_level = 0

    def handle_data(self, data):
        if self._in_title:
            self.title += data
        if self._heading_level:
            self._heading_text += data
        stripped = data.strip()
        if stripped:
            self.text_parts.append(stripped)

    @property
    def visible_text(self):
        return " ".join(self.text_parts)


class RedirectRecorder(urllib.request.HTTPRedirectHandler):
    def __init__(self):
        self.count = 0

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        self.count += 1
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def normalize_url(raw):
    raw = raw.strip()
    if not raw.startswith(("http://", "https://")):
        raw = "https://" + raw
    return raw


def fetch_url(url, timeout=REQUEST_TIMEOUT):
    """GET a URL, following redirects. Returns (status, final_url, headers,
    body_bytes, elapsed_seconds, redirect_count, error)."""
    recorder = RedirectRecorder()
    opener = urllib.request.build_opener(recorder)
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    started = time.monotonic()
    try:
        with opener.open(request, timeout=timeout) as response:
            body = response.read()
            return {
                "status": response.status,
                "final_url": response.geturl(),
                "headers": {k.lower(): v for k, v in response.headers.items()},
                "body": body,
                "elapsed": time.monotonic() - started,
                "redirects": recorder.count,
                "error": None,
            }
    except urllib.error.HTTPError as exc:
        return {
            "status": exc.code,
            "final_url": url,
            "headers": {k.lower(): v for k, v in exc.headers.items()},
            "body": b"",
            "elapsed": time.monotonic() - started,
            "redirects": recorder.count,
            "error": None,
        }
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        return {
            "status": 0,
            "final_url": url,
            "headers": {},
            "body": b"",
            "elapsed": time.monotonic() - started,
            "redirects": recorder.count,
            "error": str(exc.reason) if hasattr(exc, "reason") else str(exc),
        }


def check_url(url, timeout=REQUEST_TIMEOUT):
    """Lightweight reachability check: HEAD, falling back to GET when the
    server refuses HEAD. Returns (ok, status_or_error_string)."""
    request = urllib.request.Request(
        url, headers={"User-Agent": USER_AGENT}, method="HEAD"
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return True, response.status
    except urllib.error.HTTPError as exc:
        if exc.code in (405, 501):
            try:
                get = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
                with urllib.request.urlopen(get, timeout=timeout) as response:
                    return True, response.status
            except urllib.error.HTTPError as get_exc:
                return False, get_exc.code
            except (urllib.error.URLError, TimeoutError, OSError) as get_exc:
                return False, str(get_exc.reason) if hasattr(get_exc, "reason") else str(get_exc)
        return False, exc.code
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        return False, str(exc.reason) if hasattr(exc, "reason") else str(exc)


def is_web_link(href):
    if not href:
        return False
    lowered = href.strip().lower()
    return not lowered.startswith(
        ("#", "mailto:", "tel:", "javascript:", "data:")
    )


def find_mixed_content(page, is_https):
    """http:// resources loaded by an https page. Returns the offending URLs."""
    if not is_https:
        return []
    candidates = (
        page.stylesheets + page.scripts + [img["src"] for img in page.images]
    )
    return [value for value in candidates
            if value.strip().lower().startswith("http://")]


def detect_ai(page, html):
    """Heuristic AI-vs-human guess. Returns (verdict, signals) where each
    signal is {"strength": "strong"|"weak", "detail": str}."""
    strong, weak = [], []

    generator = page.meta.get("generator", "").lower()
    for name, strength in AI_GENERATORS.items():
        if name in generator:
            detail = f'Meta generator says "{page.meta["generator"]}"'
            (strong if strength == "strong" else weak).append(detail)
            break

    text = page.visible_text.lower()
    for phrase in BUILDER_PHRASES:
        if phrase in text or phrase in html.lower():
            strong.append(f'Page says "{phrase}" (builder badge/footer)')
            break

    for phrase in GENERIC_PHRASES:
        if phrase in text:
            weak.append(f'Generic AI-style copy: "{phrase}"')

    seen_hosts = set()
    for image in page.images:
        host = urllib.parse.urlparse(image["src"]).netloc.lower()
        if host in STOCK_PHOTO_HOSTS and host not in seen_hosts:
            seen_hosts.add(host)
            weak.append(f"Stock photo from {host}")

    points = 2 * len(strong) + len(weak)
    if points >= 4:
        verdict = "Likely AI-built"
    elif points >= 2:
        verdict = "Unclear"
    else:
        verdict = "Likely human-built"
    return verdict, [{"strength": "strong" if s in strong else "weak", "detail": s}
                     for s in strong + weak]


def analyze(url):
    url = normalize_url(url)
    report = {
        "url": url,
        "tool": f"website-bug-analyzer {VERSION}",
        "findings": [],
        "ai": {"verdict": "Unclear", "signals": []},
    }

    def add(severity, category, message):
        report["findings"].append(
            {"severity": severity, "category": category, "message": message}
        )

    result = fetch_url(url)
    report["status"] = result["status"]
    report["final_url"] = result["final_url"]
    report["redirects"] = result["redirects"]
    report["response_time_ms"] = round(result["elapsed"] * 1000)
    report["https"] = result["final_url"].startswith("https://")

    if result["error"] is not None:
        add("high", "Availability", f"Could not fetch the page: {result['error']}")
        report["score"] = 0
        report["health"] = "Poor"
        return report

    if result["status"] != 200:
        add("high", "Availability", f"Page returned HTTP {result['status']}")

    if result["redirects"] > 2:
        add("low", "Availability",
            f"Redirected {result['redirects']} times before loading")
    elif result["redirects"] > 0:
        add("low", "Availability", f"Redirected to {result['final_url']}")

    if not report["https"]:
        add("high", "Security", "Page is served over plain HTTP, not HTTPS")
    if result["elapsed"] > 3:
        add("medium", "Performance",
            f"Slow response: {result['elapsed']:.2f}s to first byte")

    content_type = result["headers"].get("content-type", "")
    if "text/html" not in content_type:
        add("high", "Content",
            f"URL does not return HTML (Content-Type: {content_type or 'unknown'})")
        report["score"] = 100 - sum(POINTS[f["severity"]] for f in report["findings"])
        report["score"] = max(0, report["score"])
        report["health"] = "Poor"
        return report

    html = result["body"].decode("utf-8", errors="replace")
    page = PageParser()
    page.feed(html)

    # Security headers.
    for header, label in SECURITY_HEADERS.items():
        if header == "strict-transport-security" and not report["https"]:
            continue  # meaningless on plain HTTP; already flagged above
        if header not in result["headers"]:
            add("medium", "Security", f"Missing security header: {label}")

    # Basic SEO.
    title = page.title.strip()
    if not title:
        add("high", "SEO", "Missing <title>")
    elif len(title) < 10:
        add("low", "SEO", f"Title is very short ({len(title)} characters)")
    elif len(title) > 70:
        add("low", "SEO", f"Title is very long ({len(title)} characters)")

    description = page.meta.get("description", "").strip()
    if not description:
        add("medium", "SEO", "Missing meta description")
    elif len(description) > 160:
        add("low", "SEO", f"Meta description is very long ({len(description)} characters)")

    if not page.canonical:
        add("low", "SEO", "No canonical link tag")
    if not page.lang:
        add("medium", "SEO", "Missing lang attribute on <html>")
    if "viewport" not in page.meta:
        add("medium", "SEO", "Missing viewport meta tag (mobile rendering)")

    h1s = [text for level, text in page.headings if level == 1]
    if not h1s:
        add("medium", "SEO", "No <h1> heading on the page")
    elif len(h1s) > 1:
        add("low", "SEO", f"Multiple <h1> headings ({len(h1s)})")
    previous_level = 0
    for level, _ in page.headings:
        if previous_level and level > previous_level + 1:
            add("low", "SEO",
                f"Heading order skips a level (h{previous_level} followed by h{level})")
            break
        previous_level = level

    # Links.
    seen_links = set()
    checked = 0
    for href in page.links:
        if not is_web_link(href) or checked >= MAX_LINKS_TO_CHECK:
            continue
        absolute = urllib.parse.urljoin(report["final_url"], href)
        if absolute in seen_links:
            continue
        seen_links.add(absolute)
        checked += 1
        ok, detail = check_url(absolute)
        if not ok:
            add("high", "Links", f"Broken link: {absolute} ({detail})")
    if len(page.links) > checked:
        add("low", "Links",
            f"Only checked the first {checked} of {len(page.links)} links")

    # Images.
    seen_images = set()
    checked_images = 0
    for image in page.images:
        src = image["src"]
        if not src:
            add("medium", "Images", "Image tag with an empty src attribute")
            continue
        if image["alt"] is None:
            add("medium", "Images", f"Image missing alt text: {src}")
        if image["width"] is None or image["height"] is None:
            add("low", "Images", f"Image without width/height (layout shift risk): {src}")
        absolute = urllib.parse.urljoin(report["final_url"], src)
        if absolute not in seen_images and checked_images < MAX_IMAGES_TO_CHECK:
            seen_images.add(absolute)
            checked_images += 1
            ok, detail = check_url(absolute)
            if not ok:
                add("high", "Images", f"Broken image: {absolute} ({detail})")

    # Mixed content.
    for value in find_mixed_content(page, report["https"]):
        add("high", "Security",
            f"Mixed content: insecure resource loaded over http:// — {value}")
        break

    # Oversized unminified assets.
    for asset in page.stylesheets + page.scripts:
        if ".min." in asset or asset.endswith(".min.css") or asset.endswith(".min.js"):
            continue
        absolute = urllib.parse.urljoin(report["final_url"], asset)
        try:
            request = urllib.request.Request(
                absolute, headers={"User-Agent": USER_AGENT}, method="HEAD"
            )
            with urllib.request.urlopen(request, timeout=REQUEST_TIMEOUT) as response:
                length = response.headers.get("Content-Length")
            if length and int(length) > LARGE_ASSET_BYTES:
                add("low", "Performance",
                    f"Large unminified asset ({int(length) // 1024} KB): {asset}")
        except (urllib.error.URLError, ValueError, OSError, TimeoutError):
            pass  # size unknown; not a finding on its own

    # AI vs human verdict.
    verdict, signals = detect_ai(page, html)
    report["ai"] = {"verdict": verdict, "signals": signals}

    score = 100 - sum(POINTS[f["severity"]] for f in report["findings"])
    report["score"] = max(0, score)
    report["health"] = "Good" if score >= 85 else "Fair" if score >= 60 else "Poor"
    return report


def format_text(report):
    lines = [
        f"website-bug-analyzer {VERSION}",
        f"URL: {report['url']}",
        f"Final URL: {report['final_url']}",
        f"HTTP {report.get('status', '-')}  |  "
        f"{'HTTPS' if report.get('https') else 'HTTP'}  |  "
        f"{report.get('response_time_ms', '-')} ms  |  "
        f"{report.get('redirects', 0)} redirect(s)",
        "",
        f"Health score: {report['score']}/100 — {report['health']}",
        "",
        "AI vs human (heuristic estimate, not proof):",
        f"  {report['ai']['verdict']}",
    ]
    for signal in report["ai"]["signals"]:
        lines.append(f"  - [{signal['strength']}] {signal['detail']}")
    if not report["ai"]["signals"]:
        lines.append("  - No AI-builder signals found.")
    lines.append("")
    counts = {"high": 0, "medium": 0, "low": 0}
    for finding in report["findings"]:
        counts[finding["severity"]] += 1
    lines.append(
        f"Findings: {len(report['findings'])} "
        f"({counts['high']} high, {counts['medium']} medium, {counts['low']} low)"
    )
    for finding in report["findings"]:
        lines.append(
            f"  [{finding['severity'].upper()}] {finding['category']}: "
            f"{finding['message']}"
        )
    if not report["findings"]:
        lines.append("  No issues found.")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Audit a website for bugs and estimate whether it was "
                    "AI-built or human-built."
    )
    parser.add_argument("url", help="URL of the page to analyze")
    parser.add_argument("--json", action="store_true",
                        help="print the full report as JSON")
    args = parser.parse_args(argv)

    report = analyze(args.url)
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print(format_text(report))

    return {"Good": 0, "Fair": 1, "Poor": 2}[report["health"]]


if __name__ == "__main__":
    sys.exit(main())
