/* Website Bug Analyzer — browser version.
   Same checks as the CLI (analyzer.py) wherever the browser allows them:
   SEO, links, images, mixed content, unminified assets, AI-vs-human signals.

   Pages are fetched through a first-party proxy (website-bug-proxy on
   Vercel) first, then public CORS proxies (allorigins.win and fallbacks),
   because a browser cannot fetch other sites directly.
   Public proxies are flaky — any of them can be down — so the app retries
   across several proxies and never reports a proxy failure as a broken
   link. If every proxy fails, the "paste HTML" mode still works: it
   analyses page source pasted by the user, entirely in the browser.
   Security headers cannot be read through a proxy and are skipped here
   — use the CLI for the full audit. */

"use strict";

/* Each proxy returns { html, httpCode }. `json` means the allorigins
   /get envelope ({ contents, status: { http_code } }); the rest return
   the raw page and the proxy's own HTTP status. */
const PROXIES = [
  {
    name: "website-bug-proxy",
    build: (url) => `https://website-bug-proxy.vercel.app/api/proxy?url=${encodeURIComponent(url)}`,
    json: true,
  },
  {
    name: "allorigins",
    build: (url) => `https://api.allorigins.win/get?url=${encodeURIComponent(url)}`,
    json: true,
  },
  {
    name: "codetabs",
    build: (url) => `https://api.codetabs.com/v1/proxy?quest=${encodeURIComponent(url)}`,
    json: false,
  },
  {
    name: "cors.lol",
    build: (url) => `https://api.cors.lol/?url=${encodeURIComponent(url)}`,
    json: false,
  },
  {
    name: "corsproxy.io",
    build: (url) => `https://corsproxy.io/?url=${encodeURIComponent(url)}`,
    json: false,
  },
];

const FETCH_TIMEOUT_MS = 20000;
const LINK_TIMEOUT_MS = 8000;
const MAX_LINKS = 15;
const MAX_IMAGES = 10;
const MAX_ASSETS = 6;
const LINK_CONCURRENCY = 5;
const LARGE_ASSET_BYTES = 200_000;

const POINTS = { high: 12, medium: 6, low: 3 };

const AI_GENERATORS = {
  durable: "strong", gamma: "strong", mixo: "strong", hocoos: "strong",
  "10web": "strong", bookmark: "strong", zyro: "strong", "wix adi": "strong",
  "jimdo dolphin": "strong", "hostinger ai": "strong",
  framer: "weak", webflow: "weak",
};

const BUILDER_PHRASES = [
  "made with durable", "built with durable", "created with durable",
  "made with gamma", "created with gamma", "made with mixo", "built with mixo",
  "made with hocoos", "built with 10web", "made with bookmark",
  "created with bookmark", "made with framer", "built with framer",
  "powered by wix", "made with wix", "created with jimdo", "powered by jimdo",
  "built with ai", "generated by ai", "created with ai",
];

const GENERIC_PHRASES = [
  "in today's fast-paced world", "unlock the power of",
  "welcome to the future of", "in the digital age", "elevate your",
  "supercharge your", "game-changer", "cutting-edge solution",
  "seamless experience", "revolutionize the way", "empower your",
  "leverage the power", "delve into",
  "take your business to the next level",
];

const STOCK_PHOTO_HOSTS = [
  "images.unsplash.com", "images.pexels.com", "cdn.pixabay.com",
  "picsum.photos", "placehold.co", "via.placeholder.com",
  "loremflickr.com", "dummyimage.com",
];

const $ = (id) => document.getElementById(id);

function normalizeUrl(raw) {
  raw = raw.trim();
  return raw.startsWith("http://") || raw.startsWith("https://")
    ? raw
    : "https://" + raw;
}

function isWebLink(href) {
  if (!href) return false;
  const lower = href.trim().toLowerCase();
  return !["#", "mailto:", "tel:", "javascript:", "data:"].some((p) => lower.startsWith(p));
}

/* Resolve a URL without throwing on garbage input. Returns null instead. */
function safeUrl(value, base) {
  try {
    return new URL(value, base).href;
  } catch (err) {
    return null;
  }
}

async function fetchWithTimeout(url, ms = FETCH_TIMEOUT_MS) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), ms);
  try {
    return await fetch(url, { signal: controller.signal });
  } finally {
    clearTimeout(timer);
  }
}

/* Fetch a page through the proxy list, first success wins. Throws only
   when every proxy failed, with a message that says so plainly. */
async function fetchPage(url, onProgress) {
  const failures = [];
  for (let i = 0; i < PROXIES.length; i++) {
    const proxy = PROXIES[i];
    if (onProgress) onProgress(`Trying proxy ${i + 1} of ${PROXIES.length} (${proxy.name})…`);
    try {
      const response = await fetchWithTimeout(proxy.build(url));
      if (!response.ok) {
        failures.push(`${proxy.name}: HTTP ${response.status}`);
        continue;
      }
      if (proxy.json) {
        let data;
        try {
          data = await response.json();
        } catch (err) {
          failures.push(`${proxy.name}: unreadable reply`);
          continue;
        }
        if (!data.contents) {
          failures.push(`${proxy.name}: empty reply`);
          continue;
        }
        return {
          html: data.contents,
          httpCode: data.status ? data.status.http_code : 200,
          via: proxy.name,
        };
      }
      const html = await response.text();
      if (!html) {
        failures.push(`${proxy.name}: empty reply`);
        continue;
      }
      return { html, httpCode: response.status, via: proxy.name };
    } catch (err) {
      failures.push(`${proxy.name}: ${err.name === "AbortError" ? "timed out" : "unreachable"}`);
    }
  }
  throw new Error(
    `All ${PROXIES.length} fetch proxies failed (${failures.join("; ")}). ` +
    "The site itself may be fine — the proxies are down. Try again, or use the " +
    "\"paste HTML\" option below the form."
  );
}

/* Run async jobs with a concurrency cap so link checks stay polite. */
async function mapLimit(items, limit, fn) {
  const results = [];
  let next = 0;
  async function worker() {
    while (next < items.length) {
      const item = items[next++];
      results.push(await fn(item));
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return results;
}

/* Link status with three outcomes. A proxy failure is "unknown" — never
   "broken": reporting every link broken just because a proxy is down
   would be a false alarm. */
async function checkLinkStatus(url) {
  try {
    const response = await fetchWithTimeout(
      `https://api.allorigins.win/get?url=${encodeURIComponent(url)}`,
      LINK_TIMEOUT_MS
    );
    if (!response.ok) return { state: "unknown", detail: `proxy HTTP ${response.status}` };
    let data;
    try {
      data = await response.json();
    } catch (err) {
      return { state: "unknown", detail: "unreadable proxy reply" };
    }
    const code = data.status && data.status.http_code;
    if (!code) return { state: "unknown", detail: "no status from proxy" };
    return code >= 200 && code < 400
      ? { state: "ok", detail: code }
      : { state: "broken", detail: code };
  } catch (err) {
    return { state: "unknown", detail: "unreachable" };
  }
}

function checkImageLoads(url) {
  return new Promise((resolve) => {
    const img = new Image();
    const timer = setTimeout(() => resolve(false), 8000);
    img.onload = () => { clearTimeout(timer); resolve(true); };
    img.onerror = () => { clearTimeout(timer); resolve(false); };
    img.src = url;
  });
}

/* Asset size via the allorigins /get envelope (raw /raw endpoint is
   unreliable). A failure only means "size unknown", never a finding. */
async function checkAssetSize(url) {
  try {
    const response = await fetchWithTimeout(
      `https://api.allorigins.win/get?url=${encodeURIComponent(url)}`,
      LINK_TIMEOUT_MS
    );
    if (!response.ok) return null;
    const data = await response.json();
    return typeof data.contents === "string" ? data.contents.length : null;
  } catch (err) {
    return null;
  }
}

function detectAi(doc, html) {
  const strong = [];
  const weak = [];

  const generator = (doc.querySelector('meta[name="generator"]')?.content || "").toLowerCase();
  for (const [name, strength] of Object.entries(AI_GENERATORS)) {
    if (generator.includes(name)) {
      const detail = `Meta generator says "${doc.querySelector('meta[name="generator"]').content}"`;
      (strength === "strong" ? strong : weak).push(detail);
      break;
    }
  }

  const text = (doc.body ? doc.body.innerText : "").toLowerCase();
  const haystack = text + " " + html.toLowerCase();
  for (const phrase of BUILDER_PHRASES) {
    if (haystack.includes(phrase)) {
      strong.push(`Page says "${phrase}" (builder badge/footer)`);
      break;
    }
  }
  for (const phrase of GENERIC_PHRASES) {
    if (text.includes(phrase)) weak.push(`Generic AI-style copy: "${phrase}"`);
  }

  const seenHosts = new Set();
  for (const img of doc.images) {
    if (!img.src) continue;
    let host = "";
    try {
      host = new URL(img.src, location.href).hostname.toLowerCase();
    } catch (err) {
      continue;
    }
    if (STOCK_PHOTO_HOSTS.includes(host) && !seenHosts.has(host)) {
      seenHosts.add(host);
      weak.push(`Stock photo from ${host}`);
    }
  }

  const points = 2 * strong.length + weak.length;
  const verdict = points >= 4 ? "Likely AI-built" : points >= 2 ? "Unclear" : "Likely human-built";
  const signals = [
    ...strong.map((detail) => ({ strength: "strong", detail })),
    ...weak.map((detail) => ({ strength: "weak", detail })),
  ];
  return { verdict, signals };
}

/* The shared audit. `status` is null when the HTML was pasted by the
   user (no HTTP status to judge). `source` describes how the page was
   obtained, shown under the score. */
async function analyzeDocument({ html, url, status, elapsedMs, via, source }) {
  const findings = [];
  const add = (severity, category, message) =>
    findings.push({ severity, category, message });

  const isHttps = url.startsWith("https://");
  const doc = new DOMParser().parseFromString(html, "text/html");

  if (status !== null && status !== 200) add("high", "Availability", `Page returned HTTP ${status}`);
  if (!isHttps) add("high", "Security", "Page is served over plain HTTP, not HTTPS");
  if (elapsedMs !== null && elapsedMs > 3000) add("medium", "Performance", `Slow response: ${(elapsedMs / 1000).toFixed(2)}s to fetch`);

  // SEO basics.
  const title = (doc.title || "").trim();
  if (!title) add("high", "SEO", "Missing <title>");
  else if (title.length < 10) add("low", "SEO", `Title is very short (${title.length} characters)`);
  else if (title.length > 70) add("low", "SEO", `Title is very long (${title.length} characters)`);

  const description = (doc.querySelector('meta[name="description"]')?.content || "").trim();
  if (!description) add("medium", "SEO", "Missing meta description");
  else if (description.length > 160) add("low", "SEO", `Meta description is very long (${description.length} characters)`);

  if (!doc.querySelector('link[rel="canonical"]')) add("low", "SEO", "No canonical link tag");
  if (!doc.documentElement.getAttribute("lang")) add("medium", "SEO", "Missing lang attribute on <html>");
  if (!doc.querySelector('meta[name="viewport"]')) add("medium", "SEO", "Missing viewport meta tag (mobile rendering)");

  const h1s = doc.querySelectorAll("h1");
  if (h1s.length === 0) add("medium", "SEO", "No <h1> heading on the page");
  else if (h1s.length > 1) add("low", "SEO", `Multiple <h1> headings (${h1s.length})`);
  let previousLevel = 0;
  for (const heading of doc.querySelectorAll("h1, h2, h3, h4, h5, h6")) {
    const level = Number(heading.tagName[1]);
    if (previousLevel && level > previousLevel + 1) {
      add("low", "SEO", `Heading order skips a level (h${previousLevel} followed by h${level})`);
      break;
    }
    previousLevel = level;
  }

  // Links (capped so the page stays fast).
  const links = [];
  const seenLinks = new Set();
  for (const anchor of doc.querySelectorAll("a[href]")) {
    const href = anchor.getAttribute("href");
    if (!isWebLink(href)) continue;
    const absolute = safeUrl(href, url);
    if (!absolute || seenLinks.has(absolute)) continue;
    seenLinks.add(absolute);
    links.push(absolute);
    if (links.length >= MAX_LINKS) break;
  }
  const linkResults = await mapLimit(links, LINK_CONCURRENCY, async (link) => ({
    link, ...(await checkLinkStatus(link)),
  }));
  let unknownLinks = 0;
  for (const result of linkResults) {
    if (result.state === "broken") add("high", "Links", `Broken link: ${result.link} (${result.detail})`);
    else if (result.state === "unknown") unknownLinks++;
  }
  if (unknownLinks > 0) {
    add("low", "Links", `Could not verify ${unknownLinks} link${unknownLinks > 1 ? "s" : ""} — the proxy was unreachable, not necessarily broken`);
  }
  const totalLinks = doc.querySelectorAll("a[href]").length;
  if (totalLinks > links.length) {
    add("low", "Links", `Only checked the first ${links.length} of ${totalLinks} links`);
  }

  // Images.
  const images = Array.from(doc.images).slice(0, MAX_IMAGES);
  for (const img of images) {
    if (!img.getAttribute("src")) {
      add("medium", "Images", "Image tag with an empty src attribute");
      continue;
    }
    if (img.getAttribute("alt") === null) {
      add("medium", "Images", `Image missing alt text: ${img.src}`);
    }
    if (!img.hasAttribute("width") || !img.hasAttribute("height")) {
      add("low", "Images", `Image without width/height (layout shift risk): ${img.src}`);
    }
  }
  const imageResults = await mapLimit(images, LINK_CONCURRENCY, async (img) => ({
    src: img.src, ok: img.getAttribute("src") ? await checkImageLoads(img.src) : true,
  }));
  for (const result of imageResults) {
    if (!result.ok) add("high", "Images", `Broken image: ${result.src}`);
  }

  // Mixed content.
  if (isHttps) {
    const resources = [
      ...Array.from(doc.querySelectorAll('link[rel="stylesheet"]')).map((el) => el.href),
      ...Array.from(doc.querySelectorAll("script[src]")).map((el) => el.src),
      ...Array.from(doc.images).map((img) => img.src),
    ];
    const insecure = resources.find((src) => src.trim().toLowerCase().startsWith("http://"));
    if (insecure) add("high", "Security", `Mixed content: insecure resource loaded over http:// — ${insecure}`);
  }

  // Oversized unminified assets.
  const assets = [
    ...Array.from(doc.querySelectorAll('link[rel="stylesheet"]')).map((el) => el.href),
    ...Array.from(doc.querySelectorAll("script[src]")).map((el) => el.src),
  ].filter((src) => !src.includes(".min."))
    .slice(0, MAX_ASSETS);
  for (const asset of assets) {
    const size = await checkAssetSize(asset);
    if (size !== null && size > LARGE_ASSET_BYTES) {
      add("low", "Performance", `Large unminified asset (${Math.round(size / 1024)} KB): ${asset}`);
    }
  }

  const ai = detectAi(doc, html);
  const score = Math.max(0, 100 - findings.reduce((sum, f) => sum + POINTS[f.severity], 0));
  const health = score >= 85 ? "Good" : score >= 60 ? "Fair" : "Poor";

  return { url, status, isHttps, elapsedMs, score, health, findings, ai, via, source };
}

async function analyzeUrl(rawUrl, onProgress) {
  const url = normalizeUrl(rawUrl);
  const started = performance.now();
  const page = await fetchPage(url, onProgress);
  const elapsedMs = Math.round(performance.now() - started);
  return analyzeDocument({
    html: page.html,
    url,
    status: page.httpCode,
    elapsedMs,
    via: page.via,
    source: `fetched via ${page.via} proxy`,
  });
}

async function analyzeHtml(html, rawUrl) {
  const url = rawUrl ? normalizeUrl(rawUrl) : "https://pasted-html.local/";
  return analyzeDocument({
    html,
    url,
    status: null,
    elapsedMs: null,
    via: "pasted HTML",
    source: "HTML pasted by you — no proxy needed",
  });
}

function renderReport(report) {
  $("score-value").textContent = report.score;
  const healthEl = $("score-health");
  healthEl.textContent = report.health;
  healthEl.className = "score-health " + report.health.toLowerCase();
  const statusText = report.status !== null ? `HTTP ${report.status} · ` : "";
  const timeText = report.elapsedMs !== null ? ` · ${report.elapsedMs} ms` : "";
  $("score-basics").textContent =
    `${statusText}${report.isHttps ? "HTTPS" : "HTTP"}${timeText} · ${report.source}`;

  $("ai-verdict").textContent = report.ai.verdict;
  const signalsEl = $("ai-signals");
  signalsEl.innerHTML = "";
  if (report.ai.signals.length === 0) {
    const li = document.createElement("li");
    li.textContent = "No AI-builder signals found.";
    signalsEl.appendChild(li);
  } else {
    for (const signal of report.ai.signals) {
      const li = document.createElement("li");
      li.textContent = `[${signal.strength}] ${signal.detail}`;
      signalsEl.appendChild(li);
    }
  }

  const counts = { high: 0, medium: 0, low: 0 };
  for (const finding of report.findings) counts[finding.severity]++;
  $("findings-summary").textContent =
    `${report.findings.length} findings — ${counts.high} high, ${counts.medium} medium, ${counts.low} low. ` +
    `Security headers are not checked in the web version; use the CLI for those.`;

  const container = $("findings");
  container.innerHTML = "";
  if (report.findings.length === 0) {
    const p = document.createElement("p");
    p.textContent = "No issues found.";
    container.appendChild(p);
  }
  for (const severity of ["high", "medium", "low"]) {
    const group = report.findings.filter((f) => f.severity === severity);
    if (group.length === 0) continue;
    const section = document.createElement("div");
    section.className = `finding-group ${severity}`;
    const heading = document.createElement("h3");
    heading.textContent = `${severity} (${group.length})`;
    section.appendChild(heading);
    for (const finding of group) {
      const div = document.createElement("div");
      div.className = "finding";
      const category = document.createElement("span");
      category.className = "category";
      category.textContent = finding.category + ": ";
      div.appendChild(category);
      div.appendChild(document.createTextNode(finding.message));
      section.appendChild(div);
    }
    container.appendChild(section);
  }

  $("results").hidden = false;
  $("results").scrollIntoView({ behavior: "smooth", block: "start" });
}

function showStatus(message, isError = false) {
  const el = $("status");
  el.hidden = false;
  el.textContent = message;
  el.classList.toggle("error", isError);
}

async function runAnalysis(run) {
  const button = $("analyze-btn");
  const pasteButton = $("paste-btn");
  button.disabled = true;
  pasteButton.disabled = true;
  button.textContent = "Analyzing…";
  $("results").hidden = true;
  showStatus("Analyzing…");
  try {
    const report = await run((message) => showStatus(message));
    $("status").hidden = true;
    renderReport(report);
  } catch (err) {
    showStatus(`Could not analyze that URL: ${err.message}`, true);
  } finally {
    button.disabled = false;
    pasteButton.disabled = false;
    button.textContent = "Analyze";
  }
}

$("analyze-form").addEventListener("submit", async (event) => {
  event.preventDefault();
  const url = $("url-input").value.trim();
  if (!url) return;
  await runAnalysis((onProgress) => {
    showStatus(`Fetching ${normalizeUrl(url)}…`);
    return analyzeUrl(url, onProgress);
  });
});

$("paste-btn").addEventListener("click", async () => {
  const html = $("html-input").value.trim();
  if (!html) {
    showStatus("Paste the page HTML first (open the page, press Ctrl+U, copy all).", true);
    return;
  }
  const pageUrl = $("html-url-input").value.trim();
  await runAnalysis(() => analyzeHtml(html, pageUrl));
});

for (const chip of document.querySelectorAll(".chip")) {
  chip.addEventListener("click", () => {
    $("url-input").value = chip.dataset.url;
    $("url-input").focus();
  });
}
